#!/usr/bin/env python3
"""Generates crates/simulation/src/tables.rs: constant tables of best.aq the simulation uses.
Each entry of TABLES names the aq field, the Rust constant and its Rust element type."""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
SRC = open(os.path.expanduser("~/brasfoot-mods/src/best/aq.java"), encoding="utf-8").read()

TABLES = [
    ("pe", "CLASSIC_DERBIES", "&str", "`aq.pe`: pairs of team files whose meeting is a classic (`I.ic()`)."),
    ("ss", "CUP_ROUND_PRIZES", "i32", "`aq.ss`: national cup prize per round, from the last round backwards (`f.G.c`)."),
    ("sw", "CONTINENTAL_ROUND_PRIZES", "i32", "`aq.sw`: main continental cup prize per round, by confederation."),
    ("sx", "CLUB_WORLD_CUP_PRIZES", "i32", "`aq.sx`"),
    ("sy", "SECOND_CONTINENTAL_ROUND_PRIZES", "i32", "`aq.sy`: second continental cup prize per round, by confederation."),
    ("sz", "INTERCONTINENTAL_PRIZES", "i32", "`aq.sz`"),
    ("sv", "STATE_CUP_ROUND_PRIZES", "i32", "`aq.sv`"),
    ("sA", "SUPER_CUP_PRIZES", "i32", "`aq.sA`"),
    ("aeG", "THIRD_CONTINENTAL_ROUND_PRIZES", "i32", "`aq.aeG`: third continental cup prize per round, by confederation."),
    ("sC", "BASE_CASH", "i64", "`aq.sC`: a club's cash when its finances restart (`ah.kH`), by division."),
    ("rW", "TOP_LEAGUE_COUNTRIES", "i32", "`aq.rW`: the countries of the strongest leagues (`ah.ki()`)."),
    ("sD", "BASE_INCOME", "i32", "`aq.sD`: the income booked when a club's finances restart, by division."),
]


def declaration(field):
    m = re.search(r"public static (?:final )?[\w\[\]]+ " + field + r" = (.*?);\n", SRC, re.S)
    if not m:
        raise SystemExit(f"aq.{field} not found")
    return " ".join(m.group(1).split())


def to_rust(expr, element):
    expr = re.sub(r"new \w+(\[\])+", "", expr)
    expr = re.sub(r"(\d)L\b", r"\1", expr)
    expr = expr.replace("{", "&[").replace("}", "]")
    return expr


def shape(expr):
    depth = 0
    best = 0
    for ch in expr:
        if ch == "[":
            depth += 1
            best = max(best, depth)
        elif ch == "]":
            depth -= 1
    return best


def day_kinds():
    """best.a.g(): the sequence of b(weekday, kind) calls that give the season's days a kind."""
    src = open(os.path.expanduser("~/brasfoot-mods/src/best/a.java"), encoding="utf-8").read()
    body = src[src.index("public static void g() {"):]
    body = body[:body.index("\n   }\n")]
    pairs = re.findall(r"b\((\d+), (\d+)\);", body)
    return "/// `best.a.g()`: (weekday, kind) in order; each takes the first free day of that weekday.\n" \
        + "pub const DAY_KINDS: &[(i32, i32)] = &[" + ", ".join(f"({a}, {b})" for a, b in pairs) + "];\n"


out = ["// Generated by tools/modelgen/gen_tables.py from best.aq and best.a. Do not edit.", "//! Constant tables of `best.aq`.", ""]
for field, name, element, doc in TABLES:
    rust = to_rust(declaration(field), element)
    depth = shape(rust)
    ty = element
    for _ in range(depth):
        ty = f"&[{ty}]"
    out.append(f"/// {doc}")
    out.append(f"pub const {name}: {ty} = {rust};")
    out.append("")
out.append(day_kinds())
open(os.path.join(ROOT, "crates/simulation/src/tables.rs"), "w").write("\n".join(out))
