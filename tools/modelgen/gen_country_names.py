#!/usr/bin/env python3
"""Generates locales/pt-BR/countries.ftl: the country names of the game's
arquivos/default_lang.xml (keys P<id>) as `country-<code>`, the codes from best.ac (countries.rs)."""
import html
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
xml = open(os.path.expanduser("~/brasfoot-mods/orig/jar/arquivos/default_lang.xml"), encoding="utf-8-sig").read()
names = {int(k): html.unescape(v).strip() for k, v in re.findall(r'<entry key="P(\d+)">(.*?)</entry>', xml)}
rust = open(os.path.join(ROOT, "crates/model/src/countries.rs"), encoding="utf-8").read()
codes = {int(i): c for i, c in re.findall(r'CountryInfo \{ id: (\d+), code: "([^"]+)"', rust)}
out = ["# Generated by tools/modelgen/gen_country_names.py from the game's arquivos/default_lang.xml. Do not edit.", ""]
seen = set()
for i in sorted(codes):
    key = "country-" + codes[i].lower()
    if i in names and key not in seen:
        seen.add(key)
        out.append(f"{key} = {names[i]}")
open(os.path.join(ROOT, "locales/pt-BR/countries.ftl"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(seen), "countries")
